#!/usr/bin/env node
/**
 * Generates src/lib/social-image-hashes.ts — a map of public social image
 * paths to a short content hash. The hash is appended as a `?v=` query to
 * og:image / twitter:image URLs so Facebook, X, LinkedIn and Slack fetch a
 * fresh preview whenever the image bytes change (they cache by URL).
 *
 * Run: node scripts/social-image-hashes.mjs [--check]
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "src/lib/social-image-hashes.ts");

/** Every image that can appear in og:image / twitter:image. */
function collect() {
  const files = ["og-cover.jpg", "favicon.png"];
  for (const dir of ["blog", "og"]) {
    const abs = path.join(ROOT, "public", dir);
    if (!existsSync(abs)) continue;
    for (const f of readdirSync(abs).sort()) {
      if (/\.(jpg|jpeg|png|webp)$/i.test(f)) files.push(`${dir}/${f}`);
    }
  }
  return files.filter((f) => existsSync(path.join(ROOT, "public", f)));
}

function hashOf(rel) {
  const buf = readFileSync(path.join(ROOT, "public", rel));
  return createHash("sha256").update(buf).digest("hex").slice(0, 10);
}

const entries = collect().map((rel) => [`/${rel}`, hashOf(rel)]);

const body = `// AUTO-GENERATED by scripts/social-image-hashes.mjs — do not edit by hand.
// Run \`bun run gen:social-hashes\` after changing any social preview image.
export const SOCIAL_IMAGE_HASHES: Record<string, string> = {
${entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n")}
};
`;

const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
if (process.argv.includes("--check")) {
  if (current !== body) {
    console.error("social-image-hashes.ts is stale. Run: bun run gen:social-hashes");
    process.exit(1);
  }
  console.log(`social image hashes up to date (${entries.length} files)`);
} else {
  if (current !== body) writeFileSync(OUT, body);
  console.log(`wrote ${entries.length} social image hashes`);
}
